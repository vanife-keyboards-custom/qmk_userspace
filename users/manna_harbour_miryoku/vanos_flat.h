// vanos — Mode B "flat" (dumb) layer: runtime callbacks.
//
// Design + host side: docs/MODE-B-KANATA.md (kboards repo). The layer tables and
// the board-specific adapters live in the board's keymaps/vanos/config.h, gated on
// VANOS_FLAT_LAYER; this header is inert unless that is defined, so a board that
// does not opt in (the BM40) is untouched even if it includes it.
//
// Included ONLY by keyboards/*/keymaps/vanos/keymap.c. It DEFINES QMK weak
// callbacks (default_layer_state_set_user, rgb_matrix_indicators_user), so it must
// be included from exactly one .c per build — same rule as vanos_thumb_hold.h.
// process_record_user is NOT defined here: keymap.c owns it and calls
// vanos_flat_process_record(), so it can be merged with other process_record_user
// users later (vanos_caps_lock.h, currently compiled out).
//
// ── What Mode B is ────────────────────────────────────────────────────────────
//
// U_FLAT is one extra default layer with NO layers, tap-holds or combos: every key
// emits one plain keycode that only says which physical position was pressed
// (30 positional letters + F13–F24 for the 6 thumbs and 6 outer-pinky keys). A host
// running kanata turns that back into the full Miryoku layout. The point: with the
// Corne's TRRS link degraded, each half runs on its own USB cable, and firmware on
// one half cannot see the other half's keys — layers, home-row mods and combos
// only work if something that sees BOTH halves does them. That something is kanata.
//
// ── Entering: Flat† (tap-dance, double tap) ───────────────────────────────────
//
// TD(U_TD_U_FLAT) is generated by the Miryoku engine from MIRYOKU_LAYER_LIST
// exactly like Base†/Extra†/Tap†. The board's config.h places it on the OUTER-TOP
// PINKY key of the Nav layer (left hand) and of the Num layer (right hand):
//
//     left half:   hold Spc (Nav)  + double-tap the left outer-top pinky key
//     right half:  hold Bsp (Num)  + double-tap the right outer-top pinky key
//
// One-handed per half on purpose: on two USB cables each half is its own master
// and knows nothing about the other half's keys, so each half has to be switched
// with keys on that half. Both layers are held by that hand's primary thumb.
//
// ── Leaving: a two-key chord on the flat layer itself ─────────────────────────
//
// The flat layer has no free key, so the exit is a chord of two flat keys on the
// SAME half, detected here in process_record_user (no COMBO_ENABLE: the userspace
// puts key_combos in the introspection unit, and a chord this simple does not need
// the combo engine):
//
//     left half:   outer-top pinky (F19) + outer thumb (F13)
//     right half:  outer-top pinky (F24) + outer thumb (F18)
//
// The first key of the chord has already been sent to the host by the time the
// second arrives; clear_keyboard() releases it. kanata maps F19/F24 to nothing on
// the base layer and F13/F18 are the Esc/Del thumbs, so the stray press is an Esc
// or Del at worst — same as tapping that thumb.
//
// ── Persistence: yes, via EEPROM ─────────────────────────────────────────────
//
// Miryoku's tap-dances use default_layer_set() (RAM only). For FLAT that would
// mean re-entering Mode B on BOTH halves after every plug-in — and Mode B is now
// the daily mode, not an experiment. So a switch INTO or OUT OF FLAT is written to
// EEPROM (QMK restores the default layer at boot, quantum/keyboard.c:450), while
// Base†/Extra†/Tap† keep Miryoku's non-persistent behaviour. The trade-off is that
// a Mode-B board plugged into a machine without kanata types F-keys and positional
// letters; the exit chord above needs no host, and `qmk flash`/EEPROM reset
// (Boot† + bootmagic) clears it too.
//
// ── Signalling the mode ──────────────────────────────────────────────────────
//
// While RGB Matrix is running, all LEDs of a half in FLAT are painted a dim blue
// (rgb_matrix_indicators_user). Entering FLAT enables RGB (RAM only) so this shows
// even on a build whose EEPROM has lighting off; leaving FLAT reloads the saved
// lighting state. Host-side check, no LEDs needed: `xev`/`wev` or `kanata --debug`
// shows F13–F24 from a half in Mode B and letters+modifiers from a half in Mode A.

#pragma once

#include "quantum.h"
#include "manna_harbour_miryoku.h" // enum miryoku_layers (U_BASE, U_FLAT)

#ifdef VANOS_FLAT_LAYER

// Exit-chord keys. Overridable from the board's config.h; defaults = the flat
// layer's outer-top pinky + outer thumb of each half.
#    ifndef VANOS_FLAT_EXIT_L1
#        define VANOS_FLAT_EXIT_L1 KC_F19
#    endif
#    ifndef VANOS_FLAT_EXIT_L2
#        define VANOS_FLAT_EXIT_L2 KC_F13
#    endif
#    ifndef VANOS_FLAT_EXIT_R1
#        define VANOS_FLAT_EXIT_R1 KC_F24
#    endif
#    ifndef VANOS_FLAT_EXIT_R2
#        define VANOS_FLAT_EXIT_R2 KC_F18
#    endif

static inline bool vanos_flat_active(void) {
    return (default_layer_state & ((layer_state_t)1 << U_FLAT)) != 0;
}

// Persist FLAT transitions only. Called for every default-layer change, including
// the one QMK makes from EEPROM at boot (then state == EEPROM and the update is a
// no-op: eeconfig_update_* writes only on change).
layer_state_t default_layer_state_set_user(layer_state_t state) {
    const layer_state_t flat = (layer_state_t)1 << U_FLAT;
    const bool          into = (state & flat) != 0;
    const bool          from = (eeconfig_read_default_layer() & flat) != 0;
    if (into || from) {
        eeconfig_update_default_layer(state);
    }
#    ifdef RGB_MATRIX_ENABLE
    if (into) {
        rgb_matrix_enable_noeeprom(); // make the indicator visible even if lighting is saved off
    } else if (from) {
        rgb_matrix_reload_from_eeprom(); // back to whatever the user had
    }
#    endif
    return state;
}

#    ifdef RGB_MATRIX_ENABLE
bool rgb_matrix_indicators_user(void) {
    if (vanos_flat_active()) {
        rgb_matrix_set_color_all(0, 0, 16); // dim blue = "I am a dumb half, kanata does the thinking"
    }
    return false;
}
#    endif

// Call from process_record_user(). Returns false (consume) only when the exit chord
// completes; everything else is passed on so the flat keycodes reach the host.
static inline bool vanos_flat_process_record(uint16_t keycode, keyrecord_t *record) {
    static bool l1, l2, r1, r2;
    bool *slot = NULL;
    switch (keycode) {
        case VANOS_FLAT_EXIT_L1: slot = &l1; break;
        case VANOS_FLAT_EXIT_L2: slot = &l2; break;
        case VANOS_FLAT_EXIT_R1: slot = &r1; break;
        case VANOS_FLAT_EXIT_R2: slot = &r2; break;
        default: return true;
    }
    *slot = record->event.pressed;
    if (record->event.pressed && vanos_flat_active() && ((l1 && l2) || (r1 && r2))) {
        l1 = l2 = r1 = r2 = false;
        clear_keyboard();                             // release the chord's first key on the host
        set_single_persistent_default_layer(U_BASE);  // back to Mode A, survives replug
        return false;
    }
    return true;
}

#else // !VANOS_FLAT_LAYER

static inline bool vanos_flat_process_record(uint16_t keycode, keyrecord_t *record) {
    (void)keycode;
    (void)record;
    return true;
}

#endif // VANOS_FLAT_LAYER
